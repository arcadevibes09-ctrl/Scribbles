const STORAGE_KEY = 'suru_blossom_inline_v2';

function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) return JSON.parse(raw);
  } catch {
    // ignore
  }
  return {
    homeCursor: 0,
    streamCursor: 0,
    topicCursors: {},
    // Stores the single active inline whisper for [topicId_pageIndex]
    activePageWhisper: {}
  };
}

function saveState(state) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch {
    // ignore
  }
}

export function advanceHomeBlossomStory() {
  const state = loadState();
  const text = homeWhispers[state.homeCursor % homeWhispers.length];
  state.homeCursor += 1;
  saveState(state);
  return { text };
}

export function peekHomeBlossomStory() {
  const state = loadState();
  if (state.homeCursor === 0) return null;
  const text = homeWhispers[(state.homeCursor - 1) % homeWhispers.length];
  return { text };
}

// Hard-pressing a notebook page generates ONE short, natural line and places it
// either right at the start (slot 0) or after paragraph 1 or 2!
export function triggerPageWhisper(topicId, pageIndex = 0, totalBlocks = 3) {
  const safeId = topicId || 'general';
  const state = loadState();
  const pageKey = `${safeId}_p${pageIndex}`;

  const tCursor = state.topicCursors[safeId] || 0;
  const specificList = topicWhispers[safeId] || [];

  let line = '';
  // Alternate between topic-aware thoughts and raw human/emotional moments
  if (tCursor < specificList.length && tCursor % 2 === 0) {
    line = specificList[tCursor];
    state.topicCursors[safeId] = tCursor + 1;
  } else if (tCursor < specificList.length && state.streamCursor % 3 !== 0) {
    line = specificList[tCursor];
    state.topicCursors[safeId] = tCursor + 1;
  } else {
    line = humanMomentStream[state.streamCursor % humanMomentStream.length];
    state.streamCursor += 1;
  }

  // Pick a natural position: 0 = right at the start, 1 = after first paragraph, 2 = after second paragraph
  const maxSlot = Math.max(1, Math.min(totalBlocks, 3));
  const prevSlot = state.activePageWhisper[pageKey]?.slot ?? -1;
  const nextSlot = (prevSlot + 1) % (maxSlot + 1);

  state.activePageWhisper[pageKey] = {
    text: line,
    slot: nextSlot
  };

  saveState(state);
  return state.activePageWhisper[pageKey];
}

export function getPageWhisper(topicId, pageIndex = 0) {
  const safeId = topicId || 'general';
  const state = loadState();
  return state.activePageWhisper[`${safeId}_p${pageIndex}`] || null;
}
